/**
 * Tiny i18n: the English text is the key; other languages map it to a translation.
 * Missing translations fall back to English. Placeholders: {name}.
 */
const KEY = 'latexlocal:ui-lang';
export const LANGS = { en: 'English', 'pt-PT': 'Português (Portugal)' };

let lang = 'en';
try { const v = JSON.parse(localStorage.getItem(KEY)); if (v && LANGS[v]) lang = v; } catch { /* default */ }

export const getLang = () => lang;
export function setLang(code) {
  if (!LANGS[code]) return;
  lang = code;
  try { localStorage.setItem(KEY, JSON.stringify(code)); } catch { /* ignore */ }
}

export function t(text, params) {
  let s = (lang !== 'en' && DICT[lang]?.[text]) || text;
  if (params) s = s.replace(/\{(\w+)\}/g, (m, k) => (k in params ? String(params[k]) : m));
  return s;
}

